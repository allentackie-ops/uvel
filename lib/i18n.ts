export function guessLocale() {
  try {
    const raw = Intl.DateTimeFormat().resolvedOptions().locale || "en-US";
    const exact = LANGS.find((l) => l.id.toLowerCase() === raw.toLowerCase());
    if (exact) return exact.id;
    const pre = raw.split("-")[0].toLowerCase();
    return LANGS.find((l) => l.id.toLowerCase() === pre || l.id.toLowerCase().startsWith(`${pre}-`))?.id ?? "en-US";
  } catch {
    return "en-US";
  }
}

export function t(locale: string): Copy {
  return COPY[locale] ?? en;
}

export function langLabel(locale: string) {
  return LANGS.find((l) => l.id === locale)?.label ?? "English, US";
}

export function isRtl(locale: string) {
  return locale === "ar" || locale === "he" || locale === "fa" || locale === "ur";
}
