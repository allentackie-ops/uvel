export function themeOf(id?: string | null, custom?: Partial<BrandTheme> | null): BrandTheme {
  const base = BRAND_THEMES.find((t) => t.id === id) ?? BRAND_THEMES[0];
  if (!custom) return base;
  return { ...base, ...custom, id: base.id, name: custom.name || base.name };
}
